public class programa_par {
    public static void main(String[] args) {
        int numero = 4; // Número a verificar

        // Comprobación de paridad
        if (numero % 2 == 0) {
            System.out.println(numero + " es par.");
        } else {
            System.out.println(numero + " es impar.");
        }
    }
}
